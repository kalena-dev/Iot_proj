#!/usr/bin/env python3
"""Configure Gmail for checkout receipts and verify SMTP and IMAP access."""
import argparse
from getpass import getpass
import imaplib
import os
from pathlib import Path
import re
import smtplib
import ssl
from tempfile import NamedTemporaryFile


def configure(sender, target):
    password = ''.join(getpass('Google app password (hidden): ').split())
    if not re.fullmatch(r'[a-zA-Z0-9]{16}', password):
        raise ValueError('Enter the 16-character app password generated by Google.')
    context = ssl.create_default_context()
    with smtplib.SMTP('smtp.gmail.com', 587, timeout=15) as smtp:
        smtp.starttls(context=context)
        smtp.login(sender, password)
    print('SMTP sign-in verified.')
    with imaplib.IMAP4_SSL('imap.gmail.com', ssl_context=context, timeout=15) as imap:
        imap.login(sender, password)
        status, _ = imap.select('INBOX', readonly=True)
        if status != 'OK':
            raise ValueError('Gmail did not allow read-only inbox access.')
    print('IMAP inbox access verified.')

    settings = dict(EMAIL_ENABLED='true', SMTP_HOST='smtp.gmail.com', SMTP_PORT='587',
                    SMTP_FROM=sender, SMTP_USER=sender, SMTP_PASSWORD=password,
                    IMAP_HOST='imap.gmail.com', IMAP_PORT='993', IMAP_USER=sender,
                    IMAP_PASSWORD=password)
    original = target.read_text().splitlines() if target.exists() else []
    keep = [line for line in original if line.partition('=')[0].strip().removeprefix('export ').strip() not in settings]
    with NamedTemporaryFile(mode='w', dir=target.parent, delete=False) as new:
        try:
            new.write('\n'.join(keep + [f'{k}={v}' for k, v in settings.items()]) + '\n')
            new.flush()
            os.fsync(new.fileno())
            os.replace(new.name, target)
        finally:
            Path(new.name).unlink(missing_ok=True)
    print('Gmail settings saved privately. Restart the checkout web service to apply.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sender')
    parser.add_argument('--file', type=Path, default=Path(__file__).resolve().parents[1] / '.env')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9._%+\-]+@gmail\.com', args.sender, re.I):
        parser.error('Enter the Gmail sender address.')
    try:
        configure(args.sender, args.file)
    except (ValueError, OSError, smtplib.SMTPException, imaplib.IMAP4.error) as error:
        parser.exit(1, f'Gmail setup failed ({type(error).__name__}). Check the account, app password and connectivity.\n')
